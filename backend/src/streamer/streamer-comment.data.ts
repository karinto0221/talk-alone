const interleave = (groups: readonly (readonly string[])[]) => {
  const comments: string[] = [];
  const maxLength = Math.max(...groups.map((group) => group.length));
  for (let index = 0; index < maxLength; index += 1) {
    for (const group of groups) {
      const comment = group[index];
      if (comment) comments.push(comment);
    }
  }
  return comments;
};

const uniqueComments = [
  ...new Set([...CURATED_COMMENTS, ...interleave(generatedGroups)]),
];

export const STREAMER_COMMENTS = uniqueComments.slice(0, TARGET_COMMENT_COUNT);

if (STREAMER_COMMENTS.length !== TARGET_COMMENT_COUNT) {
  throw new Error(`Streamer comments must contain ${TARGET_COMMENT_COUNT} unique entries.`);
}
